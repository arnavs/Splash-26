"""Monte Carlo chain reaction in a 2D lump of uranium -> assets/fig-chain-reaction.tex

    python3 assets/gen/chain_reaction.py [seed]

Physics (2D, schematic but honest): each fission emits 2 or 3 neutrons (mean 2.4) in random
directions; each neutron flies an exponentially distributed distance (mean free path LAMBDA)
before interacting. If it leaves the lump it escapes; otherwise it is captured without fission
with probability CAPTURE, or causes a fission at the nearest unused nucleus.
One generation per overlay. Prints the fissions per generation (used by the frame's counter).
"""
import math, random, sys, os

SEED = int(sys.argv[1]) if len(sys.argv) > 1 else 4
R, LAMBDA, CAPTURE, GENS, NFUEL = 3.0, 1.1, 0.15, 6, 320
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "fig-chain-reaction.tex")

def run(seed):
    rnd = random.Random(seed)
    fuel = []
    while len(fuel) < NFUEL:                       # random nuclei, not too close together
        x, y = rnd.uniform(-R, R), rnd.uniform(-R, R)
        if x*x + y*y < (R-.12)**2 and all((x-a)**2 + (y-b)**2 > .2**2 for a, b in fuel):
            fuel.append((x, y))
    used = set()
    def nearest(x, y):
        k = min((i for i in range(len(fuel)) if i not in used),
                key=lambda i: (fuel[i][0]-x)**2 + (fuel[i][1]-y)**2)
        used.add(k); return k
    start = nearest(0, 0)
    gen_of = {start: 0}; front = [start]; paths = []; counts = [1]
    for g in range(1, GENS):
        nxt = []
        for k in front:
            px, py = fuel[k]
            for _ in range(3 if rnd.random() < .4 else 2):
                th = rnd.uniform(0, 2*math.pi); d = -LAMBDA*math.log(1 - rnd.random())
                ex, ey = px + d*math.cos(th), py + d*math.sin(th)
                if ex*ex + ey*ey > R*R:            # escapes: draw it leaving the lump
                    t = d
                    while (px+t*math.cos(th))**2 + (py+t*math.sin(th))**2 > R*R: t -= .02
                    t += .55
                    paths.append(("esc", g, px, py, px+t*math.cos(th), py+t*math.sin(th)))
                elif rnd.random() < CAPTURE:
                    paths.append(("cap", g, px, py, ex, ey))
                else:
                    j = nearest(ex, ey); gen_of[j] = g; nxt.append(j)
                    paths.append(("fis", g, px, py, *fuel[j]))
        front = nxt; counts.append(len(nxt))
    return fuel, gen_of, paths, counts

fuel, gen_of, paths, counts = run(SEED)
o = [f"""% fig-chain-reaction.tex -- generated by gen/chain_reaction.py (seed {SEED}). Do not hand-edit.
% Monte Carlo: R={R}, mean free path={LAMBDA}, capture={CAPTURE}, nu=2 or 3 (mean 2.4).
% Fissions per generation: {counts}
% Pale = uranium waiting; orange = hit this generation; flash = has split.
% Gray arrows = neutrons that escape the lump; x = captured without fission.
\\begin{{tikzpicture}}[scale=.82]
\\path (-{R+.7},-{R+.7}) rectangle ({R+.7},{R+.7});
\\draw[black!25, line width=1pt] (0,0) circle ({R});
"""]
for i, (x, y) in enumerate(fuel):
    g = gen_of.get(i)
    if g is None:
        o.append(f"\\fill[fissionc!25] ({x:.2f},{y:.2f}) circle (.07);\n")
    else:
        if g > 0: o.append(f"\\fill<-{g}>[fissionc!25] ({x:.2f},{y:.2f}) circle (.07);\n")
        o.append(f"\\fill<{g+1}>[fissionc, draw=fissionc!60!black] ({x:.2f},{y:.2f}) circle (.11);\n")
        o.append(f"\\shade<{g+2}->[inner color=fissionc!90, outer color=white] ({x:.2f},{y:.2f}) circle (.26);\n")
        o.append(f"\\fill<{g+2}->[fissionc!80!yellow] ({x:.2f},{y:.2f}) circle (.06);\n")
for kind, g, x1, y1, x2, y2 in paths:
    dx, dy = x2-x1, y2-y1; L = math.hypot(dx, dy) or 1; a = .12/L
    sx, sy = x1+dx*a, y1+dy*a
    if kind == "fis":
        b = 1 - .14/L
        o.append(f"\\draw<{g+1}->[-{{Stealth[length=3.5pt]}}, black!60] ({sx:.2f},{sy:.2f}) -- ({x1+dx*b:.2f},{y1+dy*b:.2f});\n")
    elif kind == "esc":
        o.append(f"\\draw<{g+1}->[-{{Stealth[length=3.5pt]}}, black!30, dashed] ({sx:.2f},{sy:.2f}) -- ({x2:.2f},{y2:.2f});\n")
    else:
        o.append(f"\\draw<{g+1}->[black!35] ({sx:.2f},{sy:.2f}) -- ({x2:.2f},{y2:.2f}); "
                 f"\\node<{g+1}->[black!45, font=\\scriptsize] at ({x2:.2f},{y2:.2f}) {{$\\times$}};\n")
o.append(f"\\only<1>{{\\draw[-{{Stealth[length=4pt]}}, black!60, thick] (-{R+.6},.3) -- ({fuel[min(gen_of, key=gen_of.get)][0]-.15:.2f},{fuel[min(gen_of, key=gen_of.get)][1]:.2f});}}\n")
o.append("\\end{tikzpicture}\n")
open(OUT, "w").write("".join(o))
print("fissions per generation:", counts, " total:", sum(counts))
