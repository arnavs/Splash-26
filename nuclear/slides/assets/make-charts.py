"""make-charts.py -- turns the Our World in Data CSVs (fetched by fetch.sh) into pgfplots figures.

    python3 assets/make-charts.py        (from slides/)

Writes assets/fig-stockpiles.tex and assets/fig-tests.tex. Both are \\input by actual-content.tex
(through \\maybeinput, so the deck still compiles before the data exists).
OWID CSVs look like: Entity,Code,Year,<value column>[,...]
"""
import csv, os, sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")


def read(name):
    path = os.path.join(DATA, name)
    with open(path, newline="", encoding="utf-8") as f:
        head = f.read(200)
        if head.lstrip().startswith("<"):
            sys.exit(f"{name} is HTML, not CSV: the OWID slug is probably wrong.")
        f.seek(0)
        rows = list(csv.reader(f))
    header, body = rows[0], rows[1:]
    return header, body


def series(name):
    """{entity: {year: value}} using the first numeric column after Year."""
    header, body = read(name)
    yi = header.index("Year")
    vi = yi + 1
    out = defaultdict(dict)
    for r in body:
        try:
            out[r[0]][int(r[yi])] = float(r[vi])
        except (ValueError, IndexError):
            pass
    return out, header[vi]


def coords(d):
    return " ".join(f"({y},{v:g})" for y, v in sorted(d.items()))


# ---- warheads over time: US, Russia, everyone else ----
s, col = series("owid-stockpiles.csv")
us = s.get("United States", {})
ru = s.get("Russia", {})
others = defaultdict(float)
for ent, d in s.items():
    if ent in ("United States", "Russia", "World") or ent.startswith("OWID"):
        continue
    for y, v in d.items():
        others[y] += v
peak_year, peak = max(((y, us.get(y, 0) + ru.get(y, 0) + others.get(y, 0)) for y in set(us) | set(ru)), key=lambda t: t[1])
last = max(us)
fig = rf"""% fig-stockpiles.tex -- generated by make-charts.py from Our World in Data ("{col}").
\begin{{tikzpicture}}
\begin{{axis}}[width=.9\textwidth, height=.62\textheight, xmin=1945, xmax={last}, ymin=0,
  axis lines=left, tick style={{black!50}}, xtick={{1950,1970,1990,2010}}, x tick label style={{/pgf/number format/1000 sep={{}}}},
  scaled y ticks=false, y tick label style={{/pgf/number format/1000 sep={{,}}}},
  label style={{font=\small}}, tick label style={{font=\footnotesize}}, ylabel={{Warheads}}, clip=false]
\addplot[slbmc, very thick] coordinates {{{coords(us)}}};
\addplot[icbmc, very thick] coordinates {{{coords(ru)}}};
\addplot[black!45, thick] coordinates {{{coords(others)}}};
\node[slbmc, font=\small\bfseries, anchor=west] at (rel axis cs:.03,.95) {{US}};
\node[icbmc, font=\small\bfseries, anchor=west] at (rel axis cs:.03,.85) {{Russia}};
\node[black!55, font=\small\bfseries, anchor=west] at (rel axis cs:.03,.75) {{everyone else}};
\only<2->{{\draw[black!50, dashed] (axis cs:{peak_year},0) -- (axis cs:{peak_year},{peak:g});
  \node[font=\small, anchor=south] at (axis cs:{peak_year},{peak:g}) {{{peak_year}: $\approx${round(peak, -3):,.0f} in total}};}}
\end{{axis}}
\end{{tikzpicture}}
"""
open(os.path.join(HERE, "fig-stockpiles.tex"), "w").write(fig)
print(f"stockpiles: peak {peak:,.0f} in {peak_year}; last year {last}")

# ---- tests per year (all countries) ----
t, col = series("owid-tests.csv")
total = defaultdict(float)
if "World" in t:
    total.update(t["World"])
else:
    for ent, d in t.items():
        if ent.startswith("OWID"):
            continue
        for y, v in d.items():
            total[y] += v
years = sorted(total)
fig = rf"""% fig-tests.tex -- generated by make-charts.py from Our World in Data ("{col}").
\begin{{tikzpicture}}
\begin{{axis}}[ybar, bar width=1.6pt, width=.9\textwidth, height=.62\textheight, xmin={years[0]-1}, xmax={years[-1]+1}, ymin=0,
  axis lines=left, tick style={{black!50}}, xtick={{1950,1970,1990,2010}}, x tick label style={{/pgf/number format/1000 sep={{}}}},
  label style={{font=\small}}, tick label style={{font=\footnotesize}}, ylabel={{Nuclear tests per year}}, clip=false]
\addplot[fill=fissionc, draw=none] coordinates {{{coords(total)}}};
\only<2->{{\draw[black!60, dashed] (axis cs:1963,0) -- (axis cs:1963,{max(total.values()):g})
  node[above, font=\scriptsize, align=center] {{1963: atmospheric\\test ban}};}}
\only<3->{{\draw[black!60, dashed] (axis cs:1996,0) -- (axis cs:1996,{max(total.values())*0.6:g})
  node[above, font=\scriptsize, align=center] {{1996: CTBT\\signed}};}}
\end{{axis}}
\end{{tikzpicture}}
"""
open(os.path.join(HERE, "fig-tests.tex"), "w").write(fig)
print(f"tests: {years[0]}-{years[-1]}, total {sum(total.values()):,.0f}, max {max(total.values()):.0f}/yr")
